const assert=require('assert');
const fs=require('fs');
const {simulateYAS}=require('../src/yas');
const {simulateYASWithFirstFlush}=require('../src/yas_first_flush');
const {householdDemand,LEVELS}=require('../src/demand');
const {assessWaterQuality}=require('../src/quality_rules');
const {validateDistributionReadiness}=require('../src/distribution_readiness');
const parse=(f)=>{const lines=fs.readFileSync(f,'utf8').trim().split(/\r?\n/);const h=lines.shift().split(',');return lines.map(r=>Object.fromEntries(r.split(',').map((v,i)=>[h[i],v])));};
const rain=parse('data/katongan_daily_rain_1996_2025.csv');
assert.strictEqual(rain.length,10958);
const sc={roof_m2:100,rc:0.8,demand_lpd:100,tank_l:5000};
const base=simulateYAS(rain,sc);
const zero=simulateYASWithFirstFlush(rain,sc,{depth_mm:0});
for(const k of ['time_reliability_pct','volume_reliability_pct','total_spillage_m3','total_unmet_m3']) assert(Math.abs(base[k]-zero[k])<1e-10,k);
const ff=simulateYASWithFirstFlush(rain,sc,{depth_mm:0.5,dry_gap_days:2,dry_day_threshold_mm:1});
assert(ff.first_flush_events>0 && ff.first_flush_total_m3>0);
assert(ff.total_inflow_m3<=base.total_inflow_m3+1e-7);
assert(ff.total_delivered_m3<=base.total_delivered_m3+1e-7);
assert.strictEqual(householdDemand(4,LEVELS.DOMESTIC_MID).household_liters_per_day,200);
assert.throws(()=>householdDemand(0,50));
const input={intended_use:'DRINKING',has_lab_report:false,lab_complete:false,sanitary_flags:{animal_droppings:true,uncovered_tank:false,unknown_roof_material:true,chemical_suspected:true,turbid:true}};
let qr=assessWaterQuality(input);
assert.strictEqual(qr.approval_status,'NOT_VERIFIED');assert.strictEqual(qr.safe_to_drink_claim,false);
assert(qr.required_verification.includes('TARGETED_CHEMICAL_TESTING'));
assert(!qr.candidate_controls.includes('CHLORINE'));
qr=assessWaterQuality({...input,has_lab_report:true,lab_complete:true});
assert.strictEqual(qr.approval_status,'NEEDS_QUALIFIED_REVIEW');assert.strictEqual(qr.safe_to_drink_claim,false);
const readiness=validateDistributionReadiness({sites:[],demandNodes:[],roadCosts:[]});
assert.strictEqual(readiness.status,'NOT_READY');assert.strictEqual(readiness.missing_inputs.length,3);
assert.throws(()=>assessWaterQuality({intended_use:'DRINKING',has_lab_report:false,lab_complete:true,sanitary_flags:input.sanitary_flags}));
console.log('PASS integrated tests: demand, quality noncertification, first flush, distribution readiness');
console.log(JSON.stringify({base_time_reliability_pct:base.time_reliability_pct,first_flush_time_reliability_pct:ff.time_reliability_pct,first_flush_diverted_m3:ff.first_flush_total_m3,first_flush_event_proxies:ff.first_flush_events},null,2));
